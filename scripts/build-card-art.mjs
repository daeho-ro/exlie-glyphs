if(letters.length<800)throw new Error('Cannot locate the wordmark in the static homepage preview.');
for(const [x,y,alpha] of letters){
  const color=field.map((v,j)=>Math.round(v+( [251,239,215][j]-v)*alpha));
  template[(89+y-top)*rowLength+1+177+x-left]=nearest(...color);
}

// For each scanline store only nontransparent runs: start, length, ink shade.
const buffers = [], sprites = {};
let offset=0;
function add(key,width,height,pixels) {
  if(width>255 || height>255)throw new Error('Sprite dimensions exceed the encoding.');
  const runs=[];
  for(let y=0;y<height;y++){
    const begin=runs.length;
    runs.push(0);
    for(let x=0;x<width;){
      const start=x,shade=Math.round(pixels[(y*width+x)*4+3]*15/255);
      do { x++; } while(x<width && Math.round(pixels[(y*width+x)*4+3]*15/255)===shade);
      if(shade){runs.push(start,x-start,shade);runs[begin]++;}
    }
  }
  const bytes=Buffer.from(runs);
  sprites[key]=[width,height,offset];
  buffers.push(bytes);
  offset+=bytes.length;
}
for(const size of SIZES){
  for(const [id, code] of Object.entries(signCodepoints)){
    const shape=byCode.get(code);
    if(shape===undefined)throw new Error('No outline for '+id+' at '+code);
    add(size+'/'+id,size,size,raster(size,size,shape,'0 0 160 192'));
  }
  const dots=[62,80,98].map(cx=>'<circle cx="'+cx+'" cy="99" r="3.5"/>').join('');
  add(size+'/…',size,size,raster(size,size,dots,'0 0 160 192'));
}
const labels=JSON.parse(await readFile(join(assets,'count-labels.json'),'utf8'));
const cssHash=createHash('sha256').update(await load('dist/assets/pretendard/pretendard.css')).digest('hex');
if(labels.source!==cssHash)throw new Error('Update the Pretendard counter shapes with python3 font-src/card-labels.py.');
for(const [word,path] of Object.entries(labels.paths)){
  const width=150,height=44;
  const pixels=raster(width,height,'<path d="'+path+'"/>');
  let first=width,last=-1;
  for(let y=0;y<height;y++)for(let x=0;x<width;x++)if(pixels[(y*width+x)*4+3]>10){first=Math.min(first,x);last=Math.max(last,x);}
  if(last<first)throw new Error('Missing count text '+word);
  const trimmed=last-first+1,crop=Buffer.alloc(trimmed*height*4);
  for(let y=0;y<height;y++)crop.set(pixels.subarray((y*width+first)*4,(y*width+last+1)*4),y*trimmed*4);
  add('label/'+word,trimmed,height,crop);
}
const meta = Buffer.from(JSON.stringify(sprites));
const sizeHeader = Buffer.alloc(8);
sizeHeader.writeUInt32BE(meta.length,0);
sizeHeader.writeUInt32BE(palette.length*3,4);
const output=join(assets,'board-art.bin');
const atlas=Buffer.concat([sizeHeader,meta,Buffer.from(palette.flat()),template,...buffers]);
if(process.argv.includes('--check')){
  if(!atlas.equals(await readFile(output)))throw new Error('Regenerate the card atlas with node scripts/build-card-art.mjs.');
} else {
  await writeFile(output,atlas);
}
