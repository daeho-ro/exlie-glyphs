function nearest(r: number, g: number, b: number) {
  const key = r*65536+g*256+b;
  const shade = lookup.get(key);
  if (shade !== undefined) return shade;
  let best=0, distance=Infinity;
  for(let i=0;i<palette.length;i++){
    const [rr,gg,bb]=palette[i], d=(rr-r)**2+(gg-g)**2+(bb-b)**2;
    if(d<distance){distance=d;best=i;}
  }
  lookup.set(key,best);
  return best;
}
