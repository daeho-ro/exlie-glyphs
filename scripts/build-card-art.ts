// For each scanline store only nontransparent runs: start, length, ink shade.
const buffers: Buffer[] = [];
const sprites: Record<string, [number, number, number]> = {};
let offset=0;
function add(key: string, width: number, height: number, pixels: Uint8Array) {
  if(width>255 || height>255)throw new Error('Sprite dimensions exceed the encoding.');
  const runs: number[] = [];
  for(let y=0;y<height;y++){
    const begin=runs.length;
    runs.push(0);
    for(let x=0;x<width;){
      const start=x,shade=Math.round(pixels[(y*width+x)*4+3]*15/255);
      do { x++; } while(x<width && Math.round(pixels[(y*width+x)*4+3]*15/255)===shade);
      if(shade){runs.push(start,x-start,shade);runs[begin]++;}
    }
  }
  const bytes=Buffer.from(runs);
  sprites[key]=[width,height,offset];
  buffers.push(bytes);
  offset+=bytes.length;
}
