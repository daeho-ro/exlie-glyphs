import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';

// The worker needs only the stable wire codes of words the reader can select.
const root = new URL('../', import.meta.url);
const context = { window: {} };
for (const name of ['assets/glyph-map', 'assets/glyph-codes', 'catalog', 'engine']) {
  const file = new URL('dist/' + name + '.js', root);
  runInNewContext(await readFile(file, 'utf8'), context, { filename: name + '.js' });
}
const { ExileReading, ExileCodes } = context.window;
const records = ExileReading.tokens.map(({ id, glyph }) => {
  const code = ExileCodes.byId[id];
  if (!code || ExileCodes.byCode[code] !== id) throw new Error('Missing or ambiguous share code for ' + id);
  return {id, code, point: glyph.codePointAt(0)};
}).sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
const table = key => JSON.stringify(Object.fromEntries(records.map(record => [record.id, record[key]])), null, 2);
const output = '// Generated by scripts/build-share-codes.mjs from the selectable reader inventory.\n'
  + 'export const selectableCodes = Object.freeze(' + table('code') + ');\n'
  + 'export const signCodepoints = Object.freeze(' + table('point') + ');\n';
await mkdir(new URL('social/', root), { recursive: true });
await writeFile(new URL('social/selectable-codes.js', root), output);
